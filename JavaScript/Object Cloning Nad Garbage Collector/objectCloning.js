// Dynamic nature means you can chnage the state and definition of an object during run time.
// Example: 
let obj = {
    name: "Vivek",
    age: 25,
    city: "Noida"
};
console.log(obj);

// Now update or change in obj
obj.address = "Noida Sec 66";

console.log(obj);

